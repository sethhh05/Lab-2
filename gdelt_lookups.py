def lookup_rows():
    """Return the FIPS lookup as a list of tuples for Spark.

    Returns
    -------
    list of tuple
        (fips, iso3, country_name) for every entry of FIPS_TO_ISO3,
        ready for ``spark.createDataFrame`` and a broadcast join
        (Step 16).
    """
    return [(fips, iso3, name)
            for fips, (iso3, name) in sorted(FIPS_TO_ISO3.items())]
